// tiles of 32px: '#' wall, '.' floor, 'C' display case (tall cover: blocks
// movement and sight), 'T' low shelf (blocks movement only), 'p' bush
// (walkable, hides you inside it), 'S' Wren's start, 'E' the exit door,
// 'R' a relic pedestal. Guard patrols are tile waypoints walked in a loop;
// lamps are tile positions that pool light (everywhere else is shadow, and
// shadow slows a guard's detection).

